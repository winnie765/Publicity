import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
fs.mkdirSync('.sites-runtime',{recursive:true});
for(const name of ['model','import','account-structure','follower-snapshots','follower-accounts','standard-workbook','top-hits','facebook-follower-analytics']){
 const source=fs.readFileSync('app/'+name+'.ts','utf8').replace(/from '\.\/([\w-]+)'/g,"from './$1.mjs'");
 fs.writeFileSync('.sites-runtime/'+name+'.mjs',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
}
const {prepareStandardWorkbook,extractSheetData}=await import('../.sites-runtime/standard-workbook.mjs');
const {defaultConfig}=await import('../.sites-runtime/model.mjs');
const {followerSeries}=await import('../.sites-runtime/follower-accounts.mjs');
const {facebookFollowerAnalytics}=await import('../.sites-runtime/facebook-follower-analytics.mjs');
const {migrateDataset}=await import('../.sites-runtime/account-structure.mjs');
const wb=new ExcelJS.Workbook();await wb.xlsx.readFile(process.argv[2]);
const empty={posts:[],followers:[],interactions:[],config:structuredClone(defaultConfig)};
const prepared=await prepareStandardWorkbook(extractSheetData(wb).filter(s=>s.name.trim()==='Followers'),empty);
const data={...empty,config:prepared.config,followers:prepared.batches[0].items};
assert.deepEqual(followerSeries(data,'account','Facebook SEEN').snapshots.slice(0,6).map(s=>s.followers),[59,101,112,191,218,240]);
assert.deepEqual(followerSeries(data,'account','Facebook GLOW').snapshots.map(s=>s.followers),[56,65,74,81,100,106,123]);
assert.deepEqual(followerSeries(data,'account','Instagram SEEN').snapshots.map(s=>s.followers),[27,35]);
assert.deepEqual(followerSeries(data,'account','Instagram GLOW').snapshots.map(s=>s.followers),[43,51]);
assert.equal(followerSeries(data,'brand','SEEN').latest.followers,430);
assert.equal(followerSeries(data,'brand','GLOW').latest.followers,174);
assert.equal(followerSeries(data,'brand','SEEN','2025-10-31').latest,undefined);
const ig=followerSeries(data,'account','Instagram SEEN');
const growth=facebookFollowerAnalytics(ig.snapshots,[],ig.raw,'Instagram SEEN');
assert.equal(growth.latest.sincePrevious,8);assert.equal(growth.latest.growth,null);
assert.equal(growth.rows.find(r=>r.key==='2026-01').followers,undefined);
const before=structuredClone(data);data.followers.push({id:'manual-example',account:'Facebook SEEN',platform:'Facebook',accountBrand:'SEEN',date:'2026-10-31',followers:450,origin:'manual'});
assert.equal(followerSeries(data,'account','Facebook SEEN').latest.followers,450);
assert.equal(followerSeries(data,'account','Facebook GLOW').latest.followers,123);
assert.equal(followerSeries(data,'account','Instagram SEEN').latest.followers,35);
assert.equal(followerSeries(data,'brand','SEEN').latest.followers,485);
assert.equal(followerSeries(data,'brand','GLOW').latest.followers,174);
const fb=followerSeries(data,'account','Facebook SEEN');const fbGrowth=facebookFollowerAnalytics(fb.snapshots,[],fb.raw,'Facebook SEEN');
assert.equal(fbGrowth.latest.sincePrevious,55);assert.equal(fbGrowth.latest.growth,null);assert.equal(fbGrowth.latest.sincePreviousPercentage,55/395*100);
const legacy={...before,followers:before.followers.map(f=>({...f,platform:'Facebook',sourcePlatform:undefined,account:'Facebook \u00b7 Shared',accountBrand:undefined,workbookAccount:f.platform==='Instagram'?'Instagram '+f.workbookAccount:'Shared',segment:f.platform==='Instagram'?'Instagram '+f.workbookAccount:f.workbookAccount}))};
const recovered=migrateDataset(legacy);assert.equal(followerSeries(recovered,'account','Instagram SEEN').latest.followers,35);assert.equal(followerSeries(recovered,'brand','GLOW').latest.followers,174);
console.log('PASS: four workbook histories, independent account growth, explicit brand totals, missing months, stale component dates, manual updates and legacy label recovery.');

const {accountSnapshots}=await import('../.sites-runtime/follower-accounts.mjs');
assert.throws(()=>accountSnapshots(before.followers),/Select one account/,'Mixed accounts cannot collapse to a single history.');
const {validate}=await import('../.sites-runtime/model.mjs');
const {inferConfig}=await import('../.sites-runtime/import.mjs');
const valid={id:'wrong-account-test',account:'Facebook GLOW',platform:'Facebook',accountBrand:'GLOW',followers:200,date:'2026-10-31',audienceScope:'account'};
validate('followers',valid,before.config);
assert.throws(()=>validate('followers',{...valid,platform:'Instagram'},before.config),/account and platform/);
assert.throws(()=>validate('followers',{...valid,accountBrand:'SEEN'},before.config),/account and brand/);
assert.throws(()=>validate('followers',{...valid,audienceScope:'platform'},before.config),/one account/);
assert.throws(()=>inferConfig([{kind:'followers',items:[{...valid,platform:'Instagram'}]}],structuredClone(defaultConfig)),/account and platform/);
assert.throws(()=>inferConfig([{kind:'followers',items:[{...valid,accountBrand:'SEEN'}]}],structuredClone(defaultConfig)),/account and brand/);
console.log('PASS: mixed-account histories and mismatched platform/brand snapshots are rejected.');
