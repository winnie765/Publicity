import fs from 'node:fs';
import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {testCompiler} from './test-support/compiler.mjs';
const load=testCompiler('.sites-runtime/post-library-navigation-tests',{transform:(source,file)=>file==='app/record-manager.tsx'?source.replace("import {useRouter,useSearchParams} from 'next/navigation';","const useRouter=()=>({push(){}});const useSearchParams=()=>new URLSearchParams();"):source});
const {default:Navigation}=await load('app/workspace-navigation.tsx'),{default:Records}=await load('app/record-manager.tsx'),{defaultConfig}=await load('app/model.ts');
const render=(C,props)=>renderToStaticMarkup(React.createElement(C,props));
const nav=render(Navigation,{page:16,platform:'Overview',postsOnly:true});
assert(nav.match(/<a[^>]*href="\/workspace\/posts"[^>]*>/)[0].includes('aria-current="page"'));
assert(nav.includes('href="/workspace/trash"'));
const trashNav=render(Navigation,{page:16,platform:'Overview',trash:true});
assert(trashNav.match(/<a[^>]*href="\/workspace\/trash"[^>]*>/)[0].includes('aria-current="page"'));
assert(!trashNav.match(/<a[^>]*href="\/workspace\/posts"[^>]*>/)[0].includes('aria-current'));
const data={config:structuredClone(defaultConfig),posts:[],followers:[],interactions:[]};
const posts=render(Records,{data,postsOnly:true});
assert(posts.includes('Post Library'));assert(posts.includes('Add Social Media Post'));
assert(!posts.includes('records-mode-tabs'));assert(!posts.includes('Every record. One workspace.'));
assert(render(Records,{data}).includes('records-mode-tabs'));
assert(render(Records,{data,initialTrash:true}).includes('Recovery retention'));
const shell=fs.readFileSync('app/workspace-shell.tsx','utf8');
assert(shell.includes('"/workspace/posts":{"initialPage":16,"initialPostsOnly":true}'));
assert(fs.existsSync('app/workspace/posts/page.tsx'));
const portal=fs.readFileSync('app/portal.tsx','utf8');
assert(portal.includes("initialPostsOnly?'Social Media Posts'"));
assert(portal.includes('postsOnly={initialPostsOnly}'));
assert(portal.includes("key={initialPostsOnly?'posts':initialRecordsTrash?'trash':'records'}"));
console.log('PASS: dedicated posts route, active navigation, post-library presentation/actions, separate trash and preserved recovery tools.');
